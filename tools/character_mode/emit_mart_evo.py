#!/usr/bin/env python3
"""QoL A1 (2026-10-24): Mart evolution items. Emits tools/character_mode/mart_evo.asm, the (evolved species, item) pairs
that src/mart_evo.asm appends to a Mart's list when the evolved species is on the active character's roster.

Everything is read from the base ROM:
  * evolutions: EvosAttacksPointers (bank $10 $5DEF, 2 bytes per species, species 1..255). Entry layouts: method 1-4
    and 7-9, 11 are 3 bytes (method, param, species), method 5 is 4, method 6 (location) is 6, (map group, map) pairs, $FF, species; the list ends at 0. A method
    with an unknown layout stops its list (--report lists any; none in this ROM). Item methods: 2 (use item), 7 (hold item, level up), 8 / 9 (Dawn Stone, by gender). Method 3 is a trade
    with a held item: Character Mode has no trading, so a Mart can't fix it (as in game_plans/tools/evo_item_census.py).
    An item edge counts only if no other non-trade edge leads to the same species.
  * item names: length-prefixed (length byte = name length + 1) from $11:4000, item 1 first.
  * Marts: GetMart (bank $45 $6DCA) returns a list from the pointer table $7DE0 (32 Marts: count, items..., $FF;
    read by ReadMart $6E78, the routine src/mart_evo.asm hooks). The priced shops (mart type 7: table $7E20, item +
    price, read by $6E9E; types 5 and 6: $7F45 / $7F6B, points) are not Marts and do not count as "sold", as BP shops
    don't elsewhere. None of them sells a Razor Claw/Fang at a money price either.
Only items no Mart sells are emitted: wCurMart holds 14 items and the largest Mart lists 11, so the list stays small.

usage: python3 emit_mart_evo.py [--report]
"""
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
ROM = REPO / "rom" / "Pokemon Prism (v0.95 build 254 Hotfix 5).gbc"
OUT = HERE / "mart_evo.asm"

EVOS_BANK, EVOS_PTRS = 0x10, 0x5DEF
ITEM_NAMES = 0x44000
MART_BANK = 0x45
MART_TABLES = ((0x7DE0, 32),)
ITEM_METHODS = {2, 7, 8, 9}
TRADE = 3
LOCATION = 6
ENTRY_LEN = {1: 3, 2: 3, 3: 3, 4: 3, 5: 4, 7: 3, 8: 3, 9: 3, 10: 2, 11: 3}   # 10: a 2-byte prefix (Eevee: 0A F1)
MART_CAP = 14


def rom_off(bank, addr):
    return bank * 0x4000 + addr - 0x4000


def item_names(d):
    names, o = {}, ITEM_NAMES
    for i in range(1, 256):
        n = d[o]
        s = ""
        for c in d[o + 1:o + n]:
            s += (chr(65 + c - 0x80) if 0x80 <= c < 0x9A else chr(97 + c - 0xA0) if 0xA0 <= c < 0xBA
                  else " " if c == 0x7F else "Poke" if c == 0x54 else "-" if c == 0xE3 else ".")
        names[i] = s
        o += n
    return names


def evolutions(d):
    """[(species, method, param, target)] and the species whose list stopped at an unknown method."""
    edges, stopped = [], []
    for s in range(1, 256):
        p = struct.unpack_from("<H", d, rom_off(EVOS_BANK, EVOS_PTRS) + 2 * (s - 1))[0]
        o = rom_off(EVOS_BANK, p)
        while d[o]:
            m = d[o]
            if m == LOCATION:                       # 6, (map group, map number) pairs, $FF, species
                q = o + 1
                while d[q] != 0xFF:
                    q += 2
                edges.append((s, m, None, d[q + 1]))
                o = q + 2
                continue
            if m not in ENTRY_LEN:
                stopped.append((s, m))
                break
            e = d[o:o + ENTRY_LEN[m]]
            if m != 10:                             # a prefix, not an edge
                edges.append((s, m, e[1], e[-1]))
            o += ENTRY_LEN[m]
    return edges, stopped


def marts(d):
    out = {}
    for table, n in MART_TABLES:
        for k in range(n):
            a = struct.unpack_from("<H", d, rom_off(MART_BANK, table) + 2 * k)[0]
            o = rom_off(MART_BANK, a)
            cnt = d[o]
            assert d[o + 1 + cnt] == 0xFF, "mart %04x not count/items/$FF" % a
            out[a] = list(d[o + 1:o + 1 + cnt])
    return out


def pairs(d):
    edges, _ = evolutions(d)
    sold = {i for lst in marts(d).values() for i in lst}
    need = [(t, it) for s, m, it, t in edges if m in ITEM_METHODS
            and not any(s2 == s and t2 == t and m2 not in ITEM_METHODS | {TRADE} for s2, m2, _, t2 in edges)]
    return [(t, it) for t, it in need if it not in sold]


def main():
    d = ROM.read_bytes()
    names = item_names(d)
    pr = pairs(d)
    if "--report" in sys.argv:
        edges, stopped = evolutions(d)
        ms = marts(d)
        print("marts: %d, largest %d items (cap %d)" % (len(ms), max(map(len, ms.values())), MART_CAP))
        print("lists stopped at an unknown method:", stopped)
        print("pairs:", [(t, names[it]) for t, it in pr])
        return 0
    assert max(map(len, marts(d).values())) + len({it for _, it in pr}) <= MART_CAP
    lines = ["; generated by tools/character_mode/emit_mart_evo.py from the base ROM; do not edit",
             "; (evolved species, item): appended to a Mart when the species is on the roster and no Mart sells the item",
             "MartEvoPairs::"]
    lines += ["\tdb %d, $%02X ; %s" % (t, it, names[it]) for t, it in pr]
    lines += ["\tdb 0", ""]
    OUT.write_text("\n".join(lines))
    print("wrote %s: %d pairs" % (OUT.relative_to(REPO), len(pr)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
